// One committed .cjs gate file per gate, shared across every hook-capable
// host (Claude Code, Cursor, Codex, Antigravity). Phase 1 of
// docs/plans/2026-08-27-one-source-of-truth-across-agent-hosts.md.
//
// Why this file exists instead of extending the bash builders in hooks.ts:
// the bash generation in hooks.ts was fixed 2026-08-27 to read stdin instead
// of a nonexistent env var, and that fix surfaced two MORE bugs on top of the
// original one — a boundary regex that could never match before a JSON
// closing quote, and a quote-extraction regex that could never match a
// JSON-escaped `\"`. Both were bash hand-parsing raw JSON with grep/sed. A
// real JSON.parse (available for free — every host that runs hooks also has
// Node, since Soloship itself installs via npx) removes that entire bug
// class rather than patching around it a third time. It also removes the
// documented macOS-grep-has-no-\b pitfall (src/AGENTS.md) since these use
// real JS RegExp, which supports \b everywhere.
//
// Each generated .cjs is self-contained (requires only Node builtins) and
// auto-detects which host invoked it from the shape of the stdin payload —
// no argv, no per-host copies, no `--host` flag to keep in sync with the
// adapter config:
//   - Claude Code and Codex CLI share byte-identical PreToolUse contracts
//     (verified live against both vendors' docs, 2026-08-27: stdin JSON with
//     {hook_event_name, tool_name, tool_input, session_id, cwd}; block via
//     exit 2 + stderr, or exit 0 + {systemMessage} JSON to warn without
//     blocking) — one code path covers both, labeled "claude" internally.
//   - Cursor's beforeShellExecution delivers a bare {command, cwd, sandbox}
//     with no tool_input wrapper — that shape alone is the signal.
//   - Antigravity wraps everything in {toolCall: {name, args}}.
// An unrecognized shape falls through to the Claude/Codex contract (the
// widest-adopted one) rather than silently no-op'ing, so a host this file
// hasn't been taught about yet still gets exit-2 blocking instead of nothing.
//
// Committed path: `scripts/soloship-hooks/`, NOT `.soloship/hooks/`. The
// first attempt used `.soloship/hooks/`, reasoning that `.soloship/.gitignore`
// only excludes `.last-update-check` (see scaffold.ts) — true, but
// irrelevant: Soloship's own repo (which dogfoods itself) has a BLANKET
// `.soloship/` line in its ROOT .gitignore, predating this plan, and git
// cannot re-include anything under a directory a parent pattern already
// excludes (`!.soloship/hooks/` is a no-op once `.soloship/` itself matches
// — git never even descends into it). Any project with a similar root rule
// would silently get gate files that install but never reach the clone —
// the exact "gate that never runs" failure Phase 0 exists to prevent, just
// moved one layer up. Editing an arbitrary project's existing .gitignore
// lines to fix this is the fragile move; a sibling directory nothing has a
// reason to already exclude is not. `scripts/` is a plain, commonly-tracked
// directory (this repo already commits `scripts/release.js`).
//
// writeCommittedGateFiles() below still defends against the general failure
// class (some OTHER project-specific ignore rule) by asking git itself
// whether each file it just wrote is ignored, and throwing loudly if so —
// same precedent as the Cursor installer's dead-path throw.
