function isGitIgnored(root: string, relativePath: string): boolean {
  try {
    // git check-ignore -q: exit 0 = ignored (no output needed, hence -q).
    execFileSync("git", ["check-ignore", "-q", relativePath], { cwd: root, stdio: "ignore" });
    return true;
  } catch (e) {
    // Exit 1 = not ignored (the expected, common case). Anything else (no
    // git, not a repo yet) means we can't ask — assume not ignored rather
    // than block installation outside a git repo.
    return false;
  }
}

// Writes _shared.cjs + every gate file into <root>/scripts/soloship-hooks/.
// Idempotent and host-agnostic: called once by whichever installer(s) run
// (Claude, Cursor, Codex, Antigravity may all be installing in the same
// pass), safe to call more than once in one `init`/`upgrade` run.
export function writeCommittedGateFiles(root: string): string[] {
  const dir = join(root, GATE_BASE_DIR, GATE_DIRNAME);
  if (!existsSync(dir)) mkdirSync(dir, { recursive: true });

  const written: string[] = [];
  const writeGate = (filename: string, source: string) => {
    // Parse-check before writing — a generated gate with a syntax error fails
    // OPEN (Cursor spawns it directly and treats a crash as "allow"), so a
    // broken generator would silently protect nothing while doctor reports
    // it installed. Same discipline already applied to the Cursor scripts.
    new Script(source, { filename });
    const full = join(dir, filename);
    writeFileSync(full, source);
    // 0o755: Cursor spawns these directly via their shebang-less path entry
    // (Node is invoked explicitly by the other three hosts' adapters, but
    // Cursor's hooks.json takes a bare path) — executable bit is load-bearing
    // there and harmless everywhere else.
    chmodSync(full, 0o755);
    const relative = join(GATE_BASE_DIR, GATE_DIRNAME, filename);
    // Defends against the general failure class (SOME project-specific
    // gitignore rule this repo's own history already proved can exist) —
    // not just the specific `.soloship/` case that motivated the directory
    // move above. A gate that installs into a path git will never commit is
    // a gate that never reaches a clone; fail loudly instead of shipping a
    // phantom protection, same precedent as the Cursor installer's dead-path
    // throw.
    if (isGitIgnored(root, relative)) {
      throw new Error(
        `Soloship wrote a gate file to ${relative}, but this project's .gitignore excludes that path — it would install but never reach a clone or cloud agent. This is a Soloship bug (the gate directory should never collide with a project's ignore rules) or a project .gitignore that needs a carve-out. Either way, fix the ignore rule before re-running init/upgrade.`
      );
    }
    written.push(relative);
  };

  writeGate("_shared.cjs", sharedHelperSource());
  for (const name of GATE_NAMES) {
    writeGate(`${name}.cjs`, GATE_SOURCE[name]());
  }

  return written;
}

// Absolute path to a gate file — used ONLY for Claude Code's
// `.claude/settings.local.json`, which is gitignored by design (per-checkout,
// never shipped to a clone), so an absolute path baked at install time is
// safe there and matches every other generated Claude command in this
// codebase.
export function gatePath(root: string, name: GateName): string {
  return join(root, GATE_BASE_DIR, GATE_DIRNAME, `${name}.cjs`);
}

// Claude's invocation: absolute path (see gatePath). No per-host argv — the
// gate file detects its caller from the stdin payload shape (see
// sharedHelperSource's detectHost).
export function gateInvocation(root: string, name: GateName): string {
  return `bash -c 'node "${gatePath(root, name)}"'`;
}

// Portable invocation for every COMMITTED config (.codex/hooks.json,
// .agents/hooks.json, and any future host config that ships in the clone).
// An absolute path baked at install time is a path that is only valid on the
// machine that ran the installer — exactly wrong for a file meant to be
// cloned elsewhere. `git rev-parse --show-toplevel` re-resolves the project
// root from wherever the host actually runs its hook commands (documented
// cwd varies by host and by version); every gate already requires git for
// its own logic, so this adds no new dependency. Cursor's own installer
// already uses a plain root-relative path for the same committed-file reason
// (`.cursor/hooks/...`, not an absolute path) — this is the same idea, just
// defended against an unknown/subdirectory cwd rather than assuming root.
export function portableGateInvocation(name: GateName): string {
  return `bash -c 'node "$(git rev-parse --show-toplevel)/${GATE_BASE_DIR}/${GATE_DIRNAME}/${name}.cjs"'`;
}
